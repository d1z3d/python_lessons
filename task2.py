# Ввод количества чисел
N = int(input("Введите количество чисел: "))

# Проверка ограничения на N
if N < 1 or N > 100000:
    print("Ошибка: N должно быть от 1 до 100000")
    exit()

# Ввод чисел через пробел
numbers = list(map(int, input("Введите числа через пробел: ").split()))
print(numbers)

# Проверка количества введённых чисел
if len(numbers) != N:
    print("Ошибка: количество чисел не соответствует N")
    exit()

# Проверка диапазона каждого числа
for num in numbers:
    if num < 1 or num > 10**9:
        print("Ошибка: каждое число должно быть от 1 до 10^9")
        exit()

# Формирование нового массива по условию: на первом месте — последний элемент, далее сдвиг на один вправо
result = [numbers[-1]] + numbers[:-1]

# Вывод результата
print(*result)